"""
Command-Line Interface for `vault-warden-ir`.

Subcommands:
  - `scan`: Run full-spectrum secret scanning (working tree + optional Git commit history),
    supply-chain dependency auditing, and static AST vulnerability analysis.
  - `audit-deps`: Run dedicated supply-chain typosquatting and lifecycle script inspection.
  - `install-hook`: Generate and install a cross-platform `.git/hooks/pre-commit` gate.
"""

from __future__ import annotations

import argparse
import json
import os
import stat
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from vault_warden import __version__
from vault_warden.ast_auditor import scan_ast_vulnerabilities
from vault_warden.git_forensics import scan_git_history, scan_working_tree
from vault_warden.ignore import WardenIgnore
from vault_warden.sarif import format_sarif_json
from vault_warden.supply_chain import scan_supply_chain

SEVERITY_RANK: Dict[str, int] = {
    "low": 1,
    "medium": 2,
    "high": 3,
    "critical": 4,
}

PRE_COMMIT_HOOK_TEMPLATE = """#!/usr/bin/env sh
# Generated by vault-warden-ir v{version}
# Cross-platform Git pre-commit security gate (POSIX sh / Git for Windows)
set -e

if command -v python3 >/dev/null 2>&1; then
    PY_CMD="python3"
elif command -v python >/dev/null 2>&1; then
    PY_CMD="python"
else
    echo "[vault-warden-ir] ERROR: Python 3.10+ interpreter not found in PATH." >&2
    exit 1
fi

echo "[vault-warden-ir] Running pre-commit secret, supply-chain, and AST security audit..."
"$PY_CMD" -m vault_warden scan --path . --format table --fail-on high --exclude-tests
"""

PRE_PUSH_HOOK_TEMPLATE = """#!/usr/bin/env sh
# Generated by vault-warden-ir v{version}
# Cross-platform Git pre-push security gate (POSIX sh / Git for Windows)
set -e

if command -v python3 >/dev/null 2>&1; then
    PY_CMD="python3"
elif command -v python >/dev/null 2>&1; then
    PY_CMD="python"
else
    echo "[vault-warden-ir] ERROR: Python 3.10+ interpreter not found in PATH." >&2
    exit 1
fi

echo "[vault-warden-ir] Running pre-push secret and security audit prior to remote push..."
"$PY_CMD" -m vault_warden scan --path . --format table --fail-on high --exclude-tests
"""


def _format_ascii_table(findings: List[Dict[str, Any]]) -> str:
    """Render findings as a clean, deterministic ASCII table with zero emojis."""
    if not findings:
        return (
            "===============================================================================\n"
            "VAULT-WARDEN-IR SECURITY REPORT: 0 FINDINGS DETECTED (STATUS: CLEAN)\n"
            "==============================================================================="
        )

    headers = ("SEVERITY", "RULE_ID", "CWE", "LOCATION", "SUMMARY")
    rows: List[Tuple[str, str, str, str, str]] = []

    for item in findings:
        sev = str(item.get("severity", "medium")).upper()
        rule_id = str(item.get("rule_id", "VW-000"))
        cwe = str(item.get("cwe_id", "CWE-000"))
        loc = f"{item.get('file_path', 'unknown')}:{item.get('line_number', 1)}"
        if item.get("commit_hash"):
            loc = f"{loc}@{str(item['commit_hash'])[:8]}"

        summary = str(item.get("description", ""))
        if item.get("masked_secret"):
            summary = f"{summary} [redacted={item['masked_secret']}]"
        elif item.get("sink_expression"):
            summary = f"{summary} [sink={item['sink_expression']}]"

        rows.append((sev, rule_id, cwe, loc, summary))

    w_sev = max(len(headers[0]), *(len(r[0]) for r in rows))
    w_rule = max(len(headers[1]), *(len(r[1]) for r in rows))
    w_cwe = max(len(headers[2]), *(len(r[2]) for r in rows))
    w_loc = min(44, max(len(headers[3]), *(len(r[3]) for r in rows)))

    sep = f"+-{'-' * w_sev}-+-{'-' * w_rule}-+-{'-' * w_cwe}-+-{'-' * w_loc}-+-{'-' * 48}-+"
    header_line = (
        f"| {headers[0]:<{w_sev}} | {headers[1]:<{w_rule}} | {headers[2]:<{w_cwe}} "
        f"| {headers[3]:<{w_loc}} | {headers[4]:<48} |"
    )

    lines = [sep, header_line, sep]
    for sev, rule_id, cwe, loc, summary in rows:
        loc_trunc = loc if len(loc) <= w_loc else "..." + loc[-(w_loc - 3) :]
        sum_trunc = summary if len(summary) <= 48 else summary[:45] + "..."
        lines.append(
            f"| {sev:<{w_sev}} | {rule_id:<{w_rule}} | {cwe:<{w_cwe}} "
            f"| {loc_trunc:<{w_loc}} | {sum_trunc:<48} |"
        )
    lines.append(sep)

    counts = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for r in rows:
        counts[r[0]] = counts.get(r[0], 0) + 1

    lines.append(
        f"TOTAL FINDINGS: {len(rows)} "
        f"(CRITICAL={counts['CRITICAL']}, HIGH={counts['HIGH']}, "
        f"MEDIUM={counts['MEDIUM']}, LOW={counts['LOW']})"
    )
    return "\n".join(lines)


def _should_fail(findings: List[Dict[str, Any]], fail_on: Optional[str]) -> bool:
    """Return True if any finding meets or exceeds the `--fail-on` severity threshold."""
    if not fail_on:
        return False
    threshold = SEVERITY_RANK.get(fail_on.lower(), 3)
    for item in findings:
        rank = SEVERITY_RANK.get(str(item.get("severity", "low")).lower(), 1)
        if rank >= threshold:
            return True
    return False


def run_scan_command(args: argparse.Namespace) -> int:
    """Execute the `scan` subcommand."""
    target_path = Path(args.path).resolve()
    if not target_path.exists():
        print(f"[vault-warden-ir] ERROR: Path does not exist: {args.path}", file=sys.stderr)
        return 2

    ignore_file_arg = getattr(args, "ignore_file", ".wardenignore")
    search_dir = target_path if target_path.is_dir() else target_path.parent
    warden_ignore = WardenIgnore.load(ignore_path=ignore_file_arg, search_dir=search_dir)

    all_findings: List[Dict[str, Any]] = []

    # 1. Working tree secrets
    secret_findings = scan_working_tree(
        target_path,
        exclude_tests=args.exclude_tests,
        include_entropy=not args.no_entropy,
        warden_ignore=warden_ignore,
    )
    all_findings.extend(f.to_dict() for f in secret_findings)

    # 2. Optional Git history forensics
    if args.git_history and args.git_history > 0:
        hist_findings = scan_git_history(
            target_path,
            max_commits=args.git_history,
            include_entropy=not args.no_entropy,
            warden_ignore=warden_ignore,
        )
        all_findings.extend(f.to_dict() for f in hist_findings)

    # 3. Supply-chain & dependency confusion audit
    sc_findings = scan_supply_chain(
        target_path,
        exclude_tests=args.exclude_tests,
        warden_ignore=warden_ignore,
    )
    all_findings.extend(f.to_dict() for f in sc_findings)

    # 4. Python & JS Static AST Security Audit
    ast_findings = scan_ast_vulnerabilities(
        target_path,
        exclude_tests=args.exclude_tests,
        warden_ignore=warden_ignore,
    )
    all_findings.extend(f.to_dict() for f in ast_findings)

    # Filter any remaining findings against warden_ignore
    all_findings = warden_ignore.filter_findings(all_findings)

    # Sort findings by severity descending, then file_path and line_number
    all_findings.sort(
        key=lambda x: (
            -SEVERITY_RANK.get(str(x.get("severity", "low")).lower(), 1),
            str(x.get("file_path", "")),
            int(x.get("line_number", 1)),
        )
    )

    out_format = args.format.lower()
    if out_format == "json":
        payload = {
            "tool": "vault-warden-ir",
            "version": __version__,
            "total_findings": len(all_findings),
            "findings": all_findings,
        }
        print(json.dumps(payload, indent=2))
    elif out_format == "sarif":
        print(format_sarif_json(all_findings, indent=2))
    else:
        print(_format_ascii_table(all_findings))

    if _should_fail(all_findings, args.fail_on):
        return 1
    return 0


def run_audit_deps_command(args: argparse.Namespace) -> int:
    """Execute the `audit-deps` subcommand."""
    target_path = Path(args.path).resolve()
    if not target_path.exists():
        print(f"[vault-warden-ir] ERROR: Path does not exist: {args.path}", file=sys.stderr)
        return 2

    sc_findings = [f.to_dict() for f in scan_supply_chain(target_path)]
    sc_findings.sort(
        key=lambda x: (
            -SEVERITY_RANK.get(str(x.get("severity", "low")).lower(), 1),
            str(x.get("file_path", "")),
            int(x.get("line_number", 1)),
        )
    )

    if args.format.lower() == "json":
        print(
            json.dumps(
                {
                    "tool": "vault-warden-ir",
                    "subcommand": "audit-deps",
                    "total_findings": len(sc_findings),
                    "findings": sc_findings,
                },
                indent=2,
            )
        )
    elif args.format.lower() == "sarif":
        print(format_sarif_json(sc_findings, indent=2))
    else:
        print(_format_ascii_table(sc_findings))

    if _should_fail(sc_findings, args.fail_on):
        return 1
    return 0


def install_pre_commit_hook(repo_dir: Path) -> Path:
    """
    Create and chmod +x a cross-platform `.git/hooks/pre-commit` script inside `repo_dir`.
    Works on both Linux/macOS and Windows (Git for Windows / POSIX sh).
    """
    git_dir = repo_dir / ".git"
    if not git_dir.is_dir():
        raise FileNotFoundError(f"No .git directory found in {repo_dir}")

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    hook_path = hooks_dir / "pre-commit"

    content = PRE_COMMIT_HOOK_TEMPLATE.format(version=__version__)
    hook_path.write_text(content, encoding="utf-8", newline="\n")

    try:
        current_mode = os.stat(hook_path).st_mode
        os.chmod(hook_path, current_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass

    return hook_path


def install_pre_push_hook(repo_dir: Path) -> Path:
    """
    Create and chmod +x a cross-platform `.git/hooks/pre-push` script inside `repo_dir`.
    Runs secret scans prior to pushing to remotes.
    """
    git_dir = repo_dir / ".git"
    if not git_dir.is_dir():
        raise FileNotFoundError(f"No .git directory found in {repo_dir}")

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    hook_path = hooks_dir / "pre-push"

    content = PRE_PUSH_HOOK_TEMPLATE.format(version=__version__)
    hook_path.write_text(content, encoding="utf-8", newline="\n")

    try:
        current_mode = os.stat(hook_path).st_mode
        os.chmod(hook_path, current_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass

    return hook_path


def install_hook(repo_dir: Path, hook_type: str = "pre-push") -> Path:
    """Install git hook (pre-push or pre-commit) based on hook_type."""
    if hook_type == "pre-commit":
        return install_pre_commit_hook(repo_dir)
    return install_pre_push_hook(repo_dir)


def run_install_hook_command(args: argparse.Namespace) -> int:
    """Execute the `install-hook` subcommand."""
    repo_path = Path(args.repo).resolve()
    hook_type = getattr(args, "type", "pre-push")
    try:
        if hook_type == "pre-commit":
            hook_file = install_pre_commit_hook(repo_path)
        elif hook_type == "both":
            install_pre_commit_hook(repo_path)
            hook_file = install_pre_push_hook(repo_path)
        else:
            hook_file = install_pre_push_hook(repo_path)
    except FileNotFoundError as exc:
        print(f"[vault-warden-ir] ERROR: {exc}", file=sys.stderr)
        return 2

    print(f"[vault-warden-ir] Installed {hook_file.name} hook at: {hook_file.name}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    """Construct the CLI argument parser."""
    parser = argparse.ArgumentParser(
        prog="vault-warden",
        description=(
            "vault-warden-ir: Blue Team DevSecOps & Incident-Response Scanner "
            "(Shannon Entropy Secrets, Git Forensics, Supply-Chain Guard, Python/JS AST Auditor)"
        ),
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"vault-warden-ir {__version__}",
    )

    subparsers = parser.add_subparsers(dest="subcommand", required=True)

    # 1. `scan` subcommand
    scan_parser = subparsers.add_parser(
        "scan",
        help="Scan directory or repository for secrets, supply-chain risks, and AST vulnerabilities",
    )
    scan_parser.add_argument(
        "--path",
        required=True,
        help="Target file or directory path to scan",
    )
    scan_parser.add_argument(
        "--git-history",
        type=int,
        default=0,
        metavar="MAX_COMMITS",
        help="Walk up to MAX_COMMITS historical Git commit diffs (git log -p -n N)",
    )
    scan_parser.add_argument(
        "--format",
        choices=("table", "json", "sarif"),
        default="table",
        help="Output report format (default: table)",
    )
    scan_parser.add_argument(
        "--fail-on",
        choices=("low", "medium", "high", "critical"),
        default=None,
        help="Exit with code 1 if any finding meets or exceeds this severity",
    )
    scan_parser.add_argument(
        "--exclude-tests",
        action="store_true",
        help="Exclude test directories and test_* files from scan",
    )
    scan_parser.add_argument(
        "--no-entropy",
        action="store_true",
        help="Disable generic Shannon entropy heuristics and run deterministic signatures only",
    )
    scan_parser.add_argument(
        "--ignore-file",
        default=".wardenignore",
        help="Path to .wardenignore configuration file (default: .wardenignore)",
    )

    # 2. `audit-deps` subcommand
    deps_parser = subparsers.add_parser(
        "audit-deps",
        help="Audit package manifests for typosquatting, unpinned versions, and malicious install hooks",
    )
    deps_parser.add_argument(
        "--path",
        required=True,
        help="Target directory or manifest file path to audit",
    )
    deps_parser.add_argument(
        "--format",
        choices=("table", "json", "sarif"),
        default="table",
        help="Output report format (default: table)",
    )
    deps_parser.add_argument(
        "--fail-on",
        choices=("low", "medium", "high", "critical"),
        default=None,
        help="Exit with code 1 if any finding meets or exceeds this severity",
    )

    # 3. `install-hook` subcommand
    hook_parser = subparsers.add_parser(
        "install-hook",
        help="Install a cross-platform .git/hooks/pre-push or pre-commit security gate",
    )
    hook_parser.add_argument(
        "--repo",
        required=True,
        help="Path to the Git repository root",
    )
    hook_parser.add_argument(
        "--type",
        choices=("pre-push", "pre-commit", "both"),
        default="pre-push",
        help="Hook type to install (default: pre-push)",
    )

    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Main entry point for `vault-warden` CLI."""
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.subcommand == "scan":
        return run_scan_command(args)
    if args.subcommand == "audit-deps":
        return run_audit_deps_command(args)
    if args.subcommand == "install-hook":
        return run_install_hook_command(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
